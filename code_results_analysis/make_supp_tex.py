SEC_A = r"""
\subsection*{1.1 Conditioning on opportunity}

A repair rate is only comparable across conditions if the conditions offer the
same opportunity to repair. If no agent holds the correct answer at Round~0, no
amount of debate can produce a correct majority by adoption, and the observed
repair rate is bounded below the rate in conditions where a correct answer is
available. We therefore partition team--questions by whether the Round~0 answer
pool contains the correct answer and report the outcome separately within each
part.

The partition follows directly from the Round~0 state defined in the main paper:
MaC, MiC and CC are the states in which at least one agent holds the correct
answer; MaW and CW are the states in which none does. We report the share of
team--questions with a correct answer available (Oracle@R0), the expected
majority-vote correctness before and after debate ($b$ and $f$), the fraction of
the available headroom that debate converts,
$(f-b)/(\text{Oracle@R0}-b)$, and the final correctness within each part of the
partition. Confidence intervals are question-cluster bootstrap intervals with
$B=2000$ and seed~42, matching the procedure used in the main paper.

%%TABLE_A%%

Two readings matter. First, the contrast between the last two columns is the
answer to the confound: holding opportunity fixed, a team reaches the correct
answer in %%A_ROOM%% of the cases where a correct answer was available but not
yet the majority, against %%A_NONE%% of the cases where no agent held it. The
gap is a factor of %%A_RATIO%%, so the prominence of adoption in the main paper
is not an artifact of correct answers being unusually available.

Second, the headroom conversion is modest: debate captures %%A_GAP%% of the
distance between the no-debate baseline and the oracle that always selects a
correct answer present in the pool. This quantity is not reported in the main
paper. It does not contradict any claim there --- it quantifies the framing of
debate as a selection mechanism rather than a performance-improvement technique,
by showing how much of the selectable signal the mechanism actually recovers.
"""

SEC_B = r"""
\subsection*{1.5 Ability rank: post-hoc definition and selection}

The survival result in the main paper relates the fate of a singleton correct
answer to the within-team ability rank of the agent holding it. Two objections
apply. The ranking is estimated from Round~0 accuracy on the same questions used
to evaluate survival, which makes it post hoc; and rank may stand in for question
difficulty or for the Round~0 state rather than for ability. We address the second
objection with a controlled regression and the first with cross-fitting.

\subsubsection*{1.5.1 Controlled regression}

We model the survival score $f$ --- the expected correctness of the Round~3
majority vote, taking values in $\{0, \tfrac{1}{3}, 1\}$ --- as a fractional
logistic regression on holder rank, with leave-team-out difficulty quintile and
Round~0 state (MiC or CC) as controls, and the visual-dependence label added for
HallusionBench. A fractional rather than binary specification is used because
dichotomizing $f$ at $0.5$ would score every three-way tie as a failure. Standard
errors are clustered by question, since the same question recurs across ten teams.

%%TABLE_B1%%

The rank effect survives the controls in every benchmark: all eight coefficients
are significant and ordered, with rank~3 holders retaining between
%%B_R3_LO%% and %%B_R3_HI%% of the odds enjoyed by rank~1 holders.

We do not include model or team fixed effects. Rank is a deterministic function
of the pair (team, holder): once the team is fixed, the ranking of its three
members is fixed, so model and team indicators jointly absorb the rank term and
leave it unidentified. Fitting that specification produces sign-reversed and
uninterpretable rank coefficients. Consequently ability rank and model identity
are not separately identified in this design, and the coefficients below should
be read as the effect of holding a lower-ranked position, which in this
experiment is inseparable from being a particular model.

\subsubsection*{1.5.2 Cross-fitted rank}

To remove the dependence between the sample used to estimate the ranking and the
sample used to evaluate survival, we split the questions of each benchmark into
two halves, estimate per-model Round~0 accuracy on one half, apply the induced
ranking to the other half, and repeat in the reverse direction. Every
team--question is therefore evaluated under a ranking estimated without it.

%%TABLE_B2%%

Of the twenty-one cells, %%B_SAME%% are unchanged to three decimal places. The
only movements occur in MME-CoT, the smallest benchmark (575 questions, so
roughly 287 per half), where the Round~0 accuracies of Pixtral and Llama-3.2
differ by $0.024$ and a half-sample estimate occasionally reverses their order.
The monotone ordering across ranks is preserved in every cell. The ranking is
thus a stable property of the models rather than a label fitted to the questions
on which it is evaluated.
"""

SEC_C = r"""
\subsection*{1.2 Visual--language bottleneck}

\paragraph{Concern.}
The debate channel carries each peer's answer and textual rationale, whereas the
evidence needed to verify a visually dependent question resides in the image. A
correct visual judgment may therefore be overwritten by a linguistically
plausible peer claim. Because questions that demand visual verification are also
harder on average, the association we report could instead reflect difficulty.
This section tests that alternative directly.

\paragraph{Axes.}
We use labels the benchmarks provide, never labels derived from accuracy, so that
the axis cannot be mechanically entangled with difficulty. HallusionBench
supplies visual-dependent (VD) and visual-supplement (VS) annotations. MMStar
supplies six categories, of which we treat coarse and fine-grained perception as
visually demanding and logical reasoning and math as language-solvable; the two
remaining categories, instance reasoning and science and technology, cannot be
assigned to either side and are excluded from the axis. MMMU provides no official
labels distinguishing visual demand, and a perception-versus-reasoning
reclassification of the six MME-CoT categories was not significant, so neither
benchmark enters this analysis.

\paragraph{Procedure.}
Strata are quintiles of leave-team-out difficulty --- the accuracy over the
Round~0 responses produced for that question by the models that do not belong to
the focal team --- as defined in the main paper. Within each stratum we form the
two-by-two table of group by event and report the Mantel--Haenszel common odds
ratio with the Robins--Breslow--Greenland variance. Two additions go beyond the
main paper: the Breslow--Day test of whether the odds ratio is homogeneous across
strata, which licenses the common-odds-ratio summary, and direct standardization,
which reweights the language-solvable group to the difficulty distribution of the
visually demanding group and so removes any difference in difficulty composition.
The expected cell required by Breslow--Day is obtained by bisection on the
defining score function rather than through the closed-form quadratic root, to
avoid sign errors in the closed form.

%%TABLE_C1%%

\paragraph{Results.}
Homogeneity is not rejected for either recovery contrast
($p=%%C_HB_REC_P%%$ on HallusionBench, $p=%%C_MS_REC_P%%$ on MMStar), so a single
odds ratio summarizes them fairly. It is rejected for MMStar damage
($\chi^2(4)=%%C_MS_DMG_CHI%%$, $p=%%C_MS_DMG_P%%$), where the stratum-specific
odds ratios range from %%C_MS_DMG_ORLO%% to %%C_MS_DMG_ORHI%% and fall below one
in the two easiest strata. This is the formal counterpart of the observation
already reported in the main paper that the MMStar damage direction holds in
three of five strata and reverses in the two easiest, where the rates sit near
the floor.

Standardization attenuates every contrast but reverses none. The recovery deficit
moves from $%%C_HB_REC_RAW%%$ to $%%C_HB_REC_STD%%$ percentage points on
HallusionBench and from $%%C_MS_REC_RAW%%$ to $%%C_MS_REC_STD%%$ on MMStar, and
the damage excess is attenuated similarly. Between %%C_SHRINK_LO%% and
%%C_SHRINK_HI%% of each raw difference is attributable to the difference in
difficulty composition; the remainder is not. Both tests point the same way:
visual demand is associated with more damage and less recovery, and that
association does not reduce to the questions being harder.

\paragraph{Interpretation and scope.}
These results establish an association that survives difficulty control. They do
not isolate a causal channel. Separating a channel bottleneck from a residual
difficulty effect would require holding the questions fixed while varying only
the form of the evidence agents exchange --- answer only, textual rationale,
rationale grounded in image references, and attached visual evidence. That
comparison requires additional generation and is left to future work. We
therefore describe the finding as a selective visual-dependence vulnerability of
language-mediated debate, and do not claim that textualization has been shown to
cause the observed damage.

%%TABLE_C2%%
"""

SEC_D = r"""
\subsection*{1.3 Open-ended answer normalization and scoring}

Just under half of the MME-CoT questions used here are open-ended
(%%D_NQ_FREE%% of %%D_NQ_TOTAL%%, giving %%D_NR_FREE%% agent responses). Scoring
such answers by string equality would mark a correct value written in a different
notation as wrong, which would depress accuracy on that subset and, more
seriously, could depress it unevenly across rounds. We therefore scored
open-ended answers with an equivalence judge. Multiple-choice answers are scored
by option-letter matching and never reach the judge.

The procedure has one branch. The final answer is first extracted from the
response by the same rule-based \texttt{parse\_final} routine used by the debate
runner, so extraction has a single source and does not involve a language model.
The extracted string is then normalized and compared with the reference; a match
settles the item as correct without a judge call. Only the remaining pairs are
sent to the judge, which is asked whether the two strings denote the same value
and answers \texttt{yes} or \texttt{no}. Verdicts are keyed on the raw
(reference, prediction) pair and cached, so a given pair always receives the same
verdict; the judge is queried at temperature $0$. A judge call that raises is
recorded as \texttt{no}.

Normalization applies exactly five rules, in order: lowercase and strip; collapse
internal whitespace; drop a trailing period; rewrite a leading \verb|(a)| to
\verb|a|; and map five unit aliases (\verb|kph| and \verb|km/h| to a common form,
\verb|mph|, \verb|sq m| and \verb|m^2| likewise). The reference may be a list, in
which case a match against any element counts.

Across the debate transcripts this produced %%D_PAIRS%% unique
(reference, prediction) pairs. Only %%D_EXACT%% were settled by normalized string
equality; the remaining %%D_JUDGED%% went to the judge, which accepted
%%D_YES%% of them (%%D_YES_PCT%%). Open-ended scoring is therefore not exact
matching --- but neither is the judge permissive.

%%TABLE_D1%%

Two properties of the judge push its verdicts toward under-counting. First,
rejecting a symbolic expression against a numeric reference is deliberate: the
instruction tells the judge to answer \texttt{no} when a symbolic form and a
specific number cannot be seen to be equal from the text alone, and one
few-shot example demonstrates it. This avoids crediting an unevaluated
expression, at the cost of rejecting cases such as $\sqrt{5}$ against $2.23$.
Second, a failed judge call is recorded as incorrect.

A third property is not deliberate and we report it as a limitation. The few-shot
examples demonstrate unit tolerance in one direction only --- a reference
carrying a unit against a bare numeric prediction --- and the judge does not
generalize to the reverse. Predictions such as \verb|110^\circ| against a
reference of \verb|110| are rejected, which costs credit on angle questions. All
three properties bias open-ended accuracy downward, never upward.

That downward bias affects the level of open-ended accuracy but largely cancels
in the quantity the paper reports, because it applies to the Round~0 and Round~3
majority votes alike.

%%TABLE_D2%%

The debate-induced change on open-ended questions is %%D_D_FREE%% against
%%D_D_MCQ%% on multiple-choice ones, a difference of %%D_D_DIFF%% with a
question-cluster bootstrap interval of %%D_D_CI%% --- indistinguishable from
zero. The much lower baseline on open-ended questions (%%D_B_FREE%% against
%%D_B_MCQ%%) is where the conservative scoring shows up. Conclusions about
debate-induced change do not depend on the question format.

The verdict cache is included as \texttt{code\_judge/equiv\_cache.json}
(%%D_PAIRS%% pairs), so open-ended scoring can be reproduced without running the
judge model. The judge instruction and its few-shot examples are reproduced in the
Prompts section.
"""

